// Calculamos las Bytecoins acumulativas requeridas (las Bytecoins NUNCA se gastan, se acumulan)
let cumulative = 0;
export const LEVELS_DATA: LevelConfig[] = RAW_LEVELS.map((lvl) => {
  const req = cumulative;
  cumulative += lvl.bytecoins;
  return {
    ...lvl,
    progressionRole: ROLES[lvl.levelInWorld - 1],
    obstacleDescription: OBSTACLE_TEXT,
    dataCores: 3,
    requiredBytecoinsToUnlock: req,
  };
});

export function getLevelById(id: number): LevelConfig {
  return LEVELS_DATA.find((l) => l.id === id) || LEVELS_DATA[0];
}

export function getLevelsByWorld(worldId: number): LevelConfig[] {
  return LEVELS_DATA.filter((l) => l.worldId === worldId);
}
